def _gap(S):
    rows = S.get('rows') or []           # [단지, 동, 전용, 준공, 매매건, 전세건, 매매중앙값, 전세중앙값]
    if len(rows) < 3: return []
    out, N = [], S.get('name', '')
    gaps = sorted(r[6] - r[7] for r in rows)
    rat = [r[7] / r[6] * 100 for r in rows if r[6]]
    t = f"{N}에서 매매와 전세가 모두 거래된 단지·면적 {len(rows)}곳을 보면, 갭의 중간값은 {_won(gaps[len(gaps) // 2])}이고 전세가율 중간값은 {statistics.median(rat):.0f}%예요."
    hi = sum(1 for v in rat if v >= 80); small = sum(1 for v in gaps if v <= 10000)
    if hi: t += f" 전세가율이 80% 이상인 곳이 {hi}곳 있어요. 집값이 조금만 내려도 전세금을 돌려주기 어려울 수 있어 세입자라면 더 꼼꼼히 확인해야 해요."
    if small: t += f" 갭이 1억 원 이하인 곳은 {small}곳이에요."
    out.append(t)
    bands = [('전용 60㎡ 이하', lambda a: a <= 60), ('60~85㎡', lambda a: 60 < a <= 85), ('85㎡ 초과', lambda a: a > 85)]
    bt = [f"{n} {statistics.median([r[7] / r[6] * 100 for r in rows if f(r[2]) and r[6]]):.0f}%" for n, f in bands if sum(1 for r in rows if f(r[2])) >= 2]
    yr = datetime.date.today().year
    new = [r[7] / r[6] * 100 for r in rows if r[3] and r[3] >= yr - 10 and r[6]]
    old = [r[7] / r[6] * 100 for r in rows if r[3] and r[3] <= yr - 30 and r[6]]
    t = ''
    if len(bt) >= 2: t += f"면적별 전세가율 중간값은 {', '.join(bt)}예요. "
    if len(new) >= 2 and len(old) >= 2:
        t += f"준공 10년 이내 단지는 {statistics.median(new):.0f}%, 30년 넘은 단지는 {statistics.median(old):.0f}%로, "
        t += "오래된 단지일수록 전세가율이 낮은 편이에요. 재건축 기대가 매매가에만 반영되기 때문이에요." if statistics.median(old) < statistics.median(new) else "이번에는 오래된 단지의 전세가율이 오히려 높았어요."
    if t: out.append(t.strip())
    return out


def _jeonse(S):
    st, tops, highs = S.get('stats') or {}, S.get('top20') or [], S.get('highs_all') or []
    out = []
    n, nh = st.get('n', 0), st.get('n_high', 0)
    if n:
        t = f"이날 신고된 전세 {n:,}건 가운데 최근 6개월 최고 전세를 넘어선 거래는 {nh:,}건({nh / n * 100:.1f}%)이에요."
        gs = [g for g in (S.get('groups') or []) if g.get('n')]
        if len(gs) > 1:
            gh = max(gs, key=lambda g: g.get('n_high', 0) / g['n'])
            t += f" 권역별로는 {_jo(gh['name'], '이', '가')} {gh.get('n_high', 0) / gh['n'] * 100:.1f}%로 경신 비율이 가장 높았어요."
        out.append(t)
    inc = [(r['dep'] - r['prev_high']) / r['prev_high'] * 100 for r in highs if r.get('prev_high')]
    if len(inc) >= 3:
        b = max((r for r in highs if r.get('prev_high')), key=lambda r: r['dep'] - r['prev_high'])
        out.append(f"최고가를 경신한 전세는 이전 최고보다 중간값으로 {statistics.median(inc):.1f}% 높게 계약됐어요. 가장 크게 오른 곳은 {b['region']} {b.get('apt') or b['umd']} 전용 {b['area']:g}㎡로, "
                   f"이전 {_won(b['prev_high'])}보다 {_won(b['dep'] - b['prev_high'])} 오른 {_won(b['dep'])}이에요.")
    if len(tops) >= 5:
        big = sum(1 for r in tops if r['area'] > 85)
        out.append(f"보증금 상위 {len(tops)}곳 중 전용 85㎡를 넘는 큰 평형이 {big}곳이에요. 상위권 전세는 주로 " + ("큰 평형이 이끌고 있어요." if big * 2 >= len(tops) else "중소형 평형도 많이 섞여 있어요."))
    return out


def _trend(S, mode):
    Pm = S.get(mode) or {}
    rows = Pm.get('rows') or []
    if len(rows) < 5: return []
    ch = [r['chg'] for r in rows if r.get('chg') is not None]
    up, dn = sum(1 for v in ch if v > 0), sum(1 for v in ch if v < 0)
    out = [f"집계한 {len(ch)}개 시군구 중 오른 곳은 {up}곳, 내린 곳은 {dn}곳이에요. 시군구 상승률의 중간값은 {statistics.median(ch):+.1f}%예요."
           + (" 오른 곳이 내린 곳보다 많아 전체적으로 오르는 흐름이에요." if up > dn * 1.5 else " 내린 곳이 더 많아 전체적으로 쉬어 가는 흐름이에요." if dn > up * 1.5 else " 오른 곳과 내린 곳이 비슷해 지역마다 엇갈리는 흐름이에요.")]
    mn = min(r.get('n_cur', 0) for r in rows)
    big = [r for r in rows if r.get('chg') is not None and abs(r['chg']) >= 5]
    thin = [r for r in big if r.get('n_cur', 0) < 30]
    if big:
        t = f"5% 넘게 움직인 곳은 {len(big)}곳이에요."
        if thin: t += f" 이 중 {len(thin)}곳은 이번 기간 거래가 30건이 안 돼서, 몇 건의 거래에 숫자가 크게 흔들렸을 수 있어요."
        out.append(t)
    return out


def add(parts, kind, S=None, day=None, mode=None):
    try:
        day = day or datetime.date.today()
        paras = []
        if S is not None:
            paras = {'gap': _gap, 'jeonse': _jeonse}.get(kind, lambda x: [])(S) if kind != 'trend' else _trend(S, mode or 'week')
        tl = TIPS.get(kind) or []
        weekly = kind != 'jeonse'                       # 매일 글은 날짜마다, 주간·월간 글은 주마다 바뀜
        tip = tl[(day.toordinal() // (7 if weekly else 1)) % len(tl)] if tl else None
        h = ''
        if paras: h += f"<h3>{'오늘 숫자 읽기' if not weekly else '숫자로 읽어 보기'}</h3>" + ''.join(f'{P}{esc(x)}</p>' for x in paras)
        if tip: h += f'<h3>알아두면 좋은 점: {esc(tip[0])}</h3>{P}{esc(tip[1])}</p>'
        if not h: return parts
        idx = max((i for i, x in enumerate(parts) if isinstance(x, str) and x.lstrip().startswith('<hr')), default=len(parts))
        return parts[:idx] + [h] + parts[idx:]
    except Exception as e:                              # 해설은 덤 – 오류가 나도 글은 올라가게
        print('해설 문단 건너뜀:', e)
        return parts
